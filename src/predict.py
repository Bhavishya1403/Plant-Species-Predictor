"""Validated prediction and trusted artifact loading helpers."""

from __future__ import annotations

import json
import math
from collections.abc import Mapping, Sequence
from numbers import Real
from pathlib import Path
from typing import Any

import joblib
import pandas as pd

from src.data import EXPECTED_FEATURE_NAMES, EXPECTED_TARGET_NAMES

ARTIFACT_FORMAT_VERSION = 1


class ArtifactError(RuntimeError):
    """Raised when model or metadata files are missing or incompatible."""


class FeatureValidationError(ValueError):
    """Raised when user-provided measurements do not match the model schema."""


def build_feature_frame(values: Mapping[str, object]) -> pd.DataFrame:
    """Validate named measurements and return one row in canonical model order."""

    expected = set(EXPECTED_FEATURE_NAMES)
    supplied = set(values)
    missing = sorted(expected - supplied)
    unexpected = sorted(supplied - expected)
    if missing or unexpected:
        details = []
        if missing:
            details.append(f"missing features: {', '.join(missing)}")
        if unexpected:
            details.append(f"unexpected features: {', '.join(unexpected)}")
        raise FeatureValidationError("; ".join(details))

    row: list[float] = []
    for name in EXPECTED_FEATURE_NAMES:
        raw_value = values[name]
        if isinstance(raw_value, bool) or not isinstance(raw_value, Real):
            raise FeatureValidationError(f"{name} must be a finite number")
        value = float(raw_value)
        if not math.isfinite(value):
            raise FeatureValidationError(f"{name} must be finite")
        row.append(value)

    return pd.DataFrame([row], columns=EXPECTED_FEATURE_NAMES)


def predict_species(
    model: Any,
    values: Mapping[str, object],
    target_names: Sequence[str] = EXPECTED_TARGET_NAMES,
) -> dict[str, object]:
    """Predict one species and expose probabilities only when the model supports them."""

    if tuple(target_names) != EXPECTED_TARGET_NAMES:
        raise FeatureValidationError("Target labels do not match the supported Iris schema")
    frame = build_feature_frame(values)
    prediction = model.predict(frame)
    if len(prediction) != 1:
        raise RuntimeError("The model returned an unexpected number of predictions")

    class_id = int(prediction[0])
    if not 0 <= class_id < len(target_names):
        raise RuntimeError(f"The model returned an unknown class id: {class_id}")

    probability_map: dict[str, float] | None = None
    if callable(getattr(model, "predict_proba", None)):
        probabilities = model.predict_proba(frame)
        model_classes = [int(value) for value in model.classes_]
        if probabilities.shape != (1, len(model_classes)):
            raise RuntimeError("The model returned an unexpected probability shape")
        probability_map = {
            target_names[class_index]: float(probabilities[0, column_index])
            for column_index, class_index in enumerate(model_classes)
        }

    return {
        "class_id": class_id,
        "class_name": target_names[class_id],
        "probabilities": probability_map,
    }


def out_of_training_range_features(
    values: Mapping[str, object],
    feature_ranges: Mapping[str, Mapping[str, float]],
) -> list[str]:
    """Return features outside training minima/maxima (a limited OOD heuristic)."""

    frame = build_feature_frame(values)
    outside: list[str] = []
    for feature_name in EXPECTED_FEATURE_NAMES:
        bounds = feature_ranges.get(feature_name)
        if bounds is None or "min" not in bounds or "max" not in bounds:
            raise FeatureValidationError(f"Missing training range for {feature_name}")
        value = float(frame.iloc[0][feature_name])
        if value < float(bounds["min"]) or value > float(bounds["max"]):
            outside.append(feature_name)
    return outside


def load_model_bundle(
    model_path: str | Path,
    metadata_path: str | Path,
) -> tuple[Any, dict[str, Any]]:
    """Load a model bundle and verify its recorded schema and artifact version.

    Joblib artifacts use Python pickle internally. Only load files generated by a
    trusted training run; loading an untrusted artifact can execute code.
    """

    model_file = Path(model_path)
    metadata_file = Path(metadata_path)
    missing = [str(path) for path in (model_file, metadata_file) if not path.is_file()]
    if missing:
        raise ArtifactError(f"Required model artifact file(s) are missing: {', '.join(missing)}")

    try:
        with metadata_file.open("r", encoding="utf-8") as handle:
            metadata = json.load(handle)
        model = joblib.load(model_file)
    except (OSError, json.JSONDecodeError, EOFError, ValueError, TypeError) as exc:
        raise ArtifactError(f"Could not read the model bundle: {exc}") from exc
    except Exception as exc:  # joblib may surface library-specific unpickling errors.
        raise ArtifactError(f"Could not load the model artifact: {exc}") from exc

    if not isinstance(metadata, dict):
        raise ArtifactError("Model metadata must contain a JSON object")
    if metadata.get("artifact_format_version") != ARTIFACT_FORMAT_VERSION:
        raise ArtifactError(
            "Unsupported artifact format version: "
            f"{metadata.get('artifact_format_version')!r}"
        )
    required_sections = (
        "dataset",
        "split",
        "cross_validation",
        "training",
        "evaluation",
        "feature_importance",
        "runtime",
    )
    for section in required_sections:
        if not isinstance(metadata.get(section), dict):
            raise ArtifactError(f"Model metadata is missing a valid '{section}' section")

    recorded_features = tuple(metadata["dataset"].get("feature_names", ()))
    if recorded_features != EXPECTED_FEATURE_NAMES:
        raise ArtifactError("Metadata feature schema does not match the Iris application schema")
    recorded_targets = tuple(metadata["dataset"].get("target_names", ()))
    if recorded_targets != EXPECTED_TARGET_NAMES:
        raise ArtifactError("Metadata target labels do not match the Iris application schema")

    required_metrics = (
        "accuracy",
        "precision_macro",
        "recall_macro",
        "f1_macro",
        "f1_weighted",
        "per_class",
        "confusion_matrix",
    )
    if any(metric not in metadata["evaluation"] for metric in required_metrics):
        raise ArtifactError("Evaluation metadata is incomplete")
    ranges = metadata["training"].get("feature_ranges")
    if not isinstance(ranges, dict) or set(ranges) != set(EXPECTED_FEATURE_NAMES):
        raise ArtifactError("Training feature ranges do not match the Iris feature schema")
    for feature_name, bounds in ranges.items():
        if not isinstance(bounds, dict) or not {"min", "max"}.issubset(bounds):
            raise ArtifactError(f"Training range for {feature_name} is incomplete")
        try:
            lower, upper = float(bounds["min"]), float(bounds["max"])
        except (TypeError, ValueError) as exc:
            raise ArtifactError(f"Training range for {feature_name} is not numeric") from exc
        if not math.isfinite(lower) or not math.isfinite(upper) or lower > upper:
            raise ArtifactError(f"Training range for {feature_name} is invalid")

    model_features = tuple(getattr(model, "feature_names_in_", ()))
    if model_features != EXPECTED_FEATURE_NAMES:
        raise ArtifactError("Fitted model feature schema does not match the Iris application schema")
    try:
        model_classes = tuple(int(value) for value in getattr(model, "classes_", ()))
    except (TypeError, ValueError) as exc:
        raise ArtifactError("Fitted model has invalid class labels") from exc
    if model_classes != tuple(range(len(EXPECTED_TARGET_NAMES))):
        raise ArtifactError("Fitted model classes do not match the Iris target encoding")
    return model, metadata
